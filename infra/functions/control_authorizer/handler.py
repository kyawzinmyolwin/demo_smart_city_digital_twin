"""
HTTP API Lambda authorizer for the cloud control endpoint.

Allows a request only if the bearer token in the ``Authorization`` header matches
the shared control token (constant-time compare). The token is injected as an
environment variable by Terraform (generated by a ``random_password`` resource);
the dashboard sends it as ``Authorization: Bearer <token>``.

Returns the HTTP API v2 "simple response" shape: {"isAuthorized": bool}.
"""
from __future__ import annotations

import hmac
import os


def lambda_handler(event, context):
    expected = os.environ.get("CONTROL_TOKEN", "")
    headers = event.get("headers") or {}
    # HTTP API lowercases header names; accept either casing defensively.
    auth = headers.get("authorization") or headers.get("Authorization") or ""
    token = auth[7:].strip() if auth[:7].lower() == "bearer " else auth.strip()
    ok = bool(expected) and hmac.compare_digest(token, expected)
    return {"isAuthorized": ok}
